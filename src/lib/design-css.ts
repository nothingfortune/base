import type { Token } from './design-tokens';

const HEADER = '/* Generated by npm run tokens from design/tokens*.json. Do not edit. */';
// CSS generic font families, which must stay unquoted: https://drafts.csswg.org/css-fonts-4/#generic-font-families
const GENERIC = new Set([
  'serif',
  'sans-serif',
  'monospace',
  'cursive',
  'fantasy',
  'system-ui',
  'ui-sans-serif',
  'ui-serif',
  'ui-monospace',
  'ui-rounded',
  'math',
  'emoji',
  'fangsong',
]);

/** The custom property for a dotted token path. */
export function cssName(path: string): string {
  return `--${path.split('.').join('-')}`;
}

function quoteFamily(name: string): string {
  return GENERIC.has(name) ? name : `"${name.replace(/[\\"]/g, (c) => `\\${c}`)}"`;
}

function cssValue(value: Token['value']): string {
  if (typeof value === 'number') return String(value);
  if (typeof value === 'string') return quoteFamily(value);
  if ('alias' in value) return `var(${cssName(value.alias)})`;
  if ('unit' in value) return `${String(value.value)}${value.unit}`;
  if ('colorSpace' in value) {
    const alpha = value.alpha ?? 1;
    if (value.hex !== undefined && alpha === 1) return value.hex;
    const rgb = value.components.map((c) => String(Math.round(c * 255))).join(' ');
    return alpha === 1 ? `rgb(${rgb})` : `rgb(${rgb} / ${String(alpha)})`;
  }
  return value.map(quoteFamily).join(', ');
}

function declarations(tokens: readonly Token[], indent: string): string[] {
  return tokens.map((t) => `${indent}${cssName(t.path)}: ${cssValue(t.value)};`);
}

/** Paths that would share one custom property name. */
export function cssCollisions(tokens: readonly Token[]): string[] {
  const seen = new Map<string, string>();
  const errors: string[] = [];
  for (const { path } of tokens) {
    const name = cssName(path);
    const first = seen.get(name);
    if (first === undefined) seen.set(name, path);
    else errors.push(`${name}: ${first} and ${path}`);
  }
  return errors;
}

/** The stylesheet: light values on :root, dark overrides by media query and by data-theme. */
export function emitCss(base: readonly Token[], dark: readonly Token[]): string {
  const lines = [HEADER, ':root {', ...declarations(base, '  '), '}'];
  if (dark.length > 0) {
    lines.push(
      '',
      '@media (prefers-color-scheme: dark) {',
      '  :root:not([data-theme="light"]) {',
      ...declarations(dark, '    '),
      '  }',
      '}',
      '',
      ':root[data-theme="dark"] {',
      ...declarations(dark, '  '),
      '}',
    );
  }
  return `${lines.join('\n')}\n`;
}
