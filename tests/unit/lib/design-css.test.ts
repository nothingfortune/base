import { describe, expect, it } from 'vitest';

import { cssCollisions, cssName, emitCss } from '../../../src/lib/design-css';
import type { Token } from '../../../src/lib/design-tokens';

const HEADER = '/* Generated by npm run tokens from design/tokens*.json. Do not edit. */';

const accent: Token = {
  path: 'color.accent',
  type: 'color',
  value: { colorSpace: 'srgb', components: [0, 0.4, 1], hex: '#0066ff' },
};

function one(token: Token): string {
  return emitCss([token], []).split('\n')[2] ?? '';
}

function family(value: string | readonly string[]): string {
  return one({ path: 'f', type: 'fontFamily', value });
}

describe('cssName', () => {
  it('joins the path with dashes behind --', () => {
    expect(cssName('color.bg.surface')).toBe('--color-bg-surface');
  });
});

describe('emitCss', () => {
  it('emits the exact stylesheet', () => {
    const base: Token[] = [
      accent,
      {
        path: 'color.scrim',
        type: 'color',
        value: { colorSpace: 'srgb', components: [0, 0, 0], alpha: 0.5 },
      },
      {
        path: 'color.ink',
        type: 'color',
        value: { colorSpace: 'srgb', components: [17 / 255, 17 / 255, 17 / 255] },
      },
      { path: 'color.focus', type: 'color', value: { alias: 'color.accent' } },
      { path: 'space.sm', type: 'dimension', value: { value: 8, unit: 'px' } },
      { path: 'font.family.sans', type: 'fontFamily', value: ['Segoe UI', 'system-ui'] },
    ];
    const dark: Token[] = [
      {
        path: 'color.accent',
        type: 'color',
        value: { colorSpace: 'srgb', components: [1, 1, 1], hex: '#ffffff' },
      },
    ];
    expect(emitCss(base, dark)).toBe(
      [
        HEADER,
        ':root {',
        '  --color-accent: #0066ff;',
        '  --color-scrim: rgb(0 0 0 / 0.5);',
        '  --color-ink: rgb(17 17 17);',
        '  --color-focus: var(--color-accent);',
        '  --space-sm: 8px;',
        '  --font-family-sans: "Segoe UI", system-ui;',
        '}',
        '',
        '@media (prefers-color-scheme: dark) {',
        '  :root:not([data-theme="light"]) {',
        '    --color-accent: #ffffff;',
        '  }',
        '}',
        '',
        ':root[data-theme="dark"] {',
        '  --color-accent: #ffffff;',
        '}',
        '',
      ].join('\n'),
    );
  });

  it('emits no dark blocks when dark is empty', () => {
    expect(emitCss([accent], [])).toBe(`${HEADER}\n:root {\n  --color-accent: #0066ff;\n}\n`);
  });

  it('emits rgb() when a hex is present but alpha is below 1', () => {
    const value = {
      colorSpace: 'srgb',
      components: [1, 0, 0],
      alpha: 0.25,
      hex: '#ff0000',
    } as const;
    expect(one({ path: 'c', type: 'color', value: { ...value, components: [1, 0, 0] } })).toBe(
      '  --c: rgb(255 0 0 / 0.25);',
    );
  });

  it('emits the hex when alpha is exactly 1', () => {
    const value = { colorSpace: 'srgb', components: [1, 0, 0], alpha: 1, hex: '#ff0000' } as const;
    expect(one({ path: 'c', type: 'color', value: { ...value, components: [1, 0, 0] } })).toBe(
      '  --c: #ff0000;',
    );
  });

  it('quotes a family with a space and escapes embedded quotes', () => {
    expect(family('He said "hi"')).toBe('  --f: "He said \\"hi\\"";');
  });

  it('escapes a backslash in a family', () => {
    expect(family('a\\b')).toBe('  --f: "a\\\\b";');
  });

  it('quotes a single-word family that is not a generic keyword', () => {
    expect(family('Inter')).toBe('  --f: "Inter";');
  });

  it.each([
    'serif',
    'sans-serif',
    'monospace',
    'cursive',
    'fantasy',
    'system-ui',
    'ui-sans-serif',
    'ui-serif',
    'ui-monospace',
    'ui-rounded',
    'math',
    'emoji',
    'fangsong',
  ])('leaves the generic family %s unquoted', (generic) => {
    expect(family(generic)).toBe(`  --f: ${generic};`);
  });

  it('emits a fontWeight as its number', () => {
    expect(one({ path: 'w', type: 'fontWeight', value: 950 })).toBe('  --w: 950;');
  });

  it('emits a duration with its unit', () => {
    expect(one({ path: 'd', type: 'duration', value: { value: 200, unit: 'ms' } })).toBe(
      '  --d: 200ms;',
    );
  });

  it('emits a number as is', () => {
    expect(one({ path: 'n', type: 'number', value: 1.5 })).toBe('  --n: 1.5;');
  });
});

describe('cssCollisions', () => {
  it('reports two paths that share one CSS name', () => {
    const tokens: Token[] = [
      { path: 'a.b-c', type: 'number', value: 1 },
      { path: 'a-b.c', type: 'number', value: 2 },
    ];
    expect(cssCollisions(tokens)).toEqual(['--a-b-c: a.b-c and a-b.c']);
  });

  it('reports nothing when names are distinct', () => {
    expect(cssCollisions([accent])).toEqual([]);
  });
});

describe('generic family case', () => {
  it('leaves a generic family unquoted whatever its case', () => {
    expect(family('Sans-Serif')).toBe('  --f: Sans-Serif;');
  });
});
